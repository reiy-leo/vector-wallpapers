// 把 dist/ 打包成 worker-inline/assets.generated.ts，供 wrangler.inline.jsonc 部署（见 worker-inline/entry.ts）。
// 同时把 public/_headers 里 "/*" 段的安全头（CSP 等）带进 Worker 响应。
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative } from 'node:path';

const root = new URL('../dist/', import.meta.url).pathname;
const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.json': 'application/json',
  '.txt': 'text/plain; charset=utf-8',
  '.xml': 'application/xml; charset=utf-8',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.webp': 'image/webp',
};
const SKIP = new Set(['_headers', '_redirects']);

const assets = {};
(function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    if (SKIP.has(f) || f.endsWith('.map')) continue;
    const t = TYPES[extname(f)] ?? 'application/octet-stream';
    const bin = !(t.startsWith('text/') || t === 'image/svg+xml' || t === 'application/json' || t.startsWith('application/xml'));
    assets['/' + relative(root, p)] = { t, b: bin, d: bin ? readFileSync(p).toString('base64') : readFileSync(p, 'utf8') };
  }
})(root);

// public/_headers 的 "/*" 段：缩进行里的 "Name: value"
const headers = {};
let inGlobal = false;
for (const line of readFileSync(new URL('../public/_headers', import.meta.url), 'utf8').split('\n')) {
  if (/^\S/.test(line)) { inGlobal = line.trim() === '/*'; continue; }
  const m = inGlobal && line.match(/^\s+([A-Za-z-]+):\s*(.+)$/);
  if (m && !line.trim().startsWith('#')) headers[m[1]] = m[2].trim();
}

writeFileSync(
  new URL('../worker-inline/assets.generated.ts', import.meta.url),
  '// Generated by scripts/build-inline-assets.mjs. Do not edit.\n' +
    `export const GLOBAL_HEADERS: Record<string, string> = ${JSON.stringify(headers)};\n` +
    `export const INLINE_ASSETS: Record<string, { t: string; b: boolean; d: string }> = ${JSON.stringify(assets)};\n`,
);
console.log(`inlined ${Object.keys(assets).length} files, ${Object.keys(headers).length} headers`);
