/**
 * HTTP 状态码 → 简短中文释义（Rei 2026-10-13：界面里出现的任何 HTTP 状态码都要带中文说明）。
 */
const GLOSS: Record<number, string> = {
  400: '请求无效',
  401: '未登录',
  403: '禁止访问',
  404: '未找到',
  405: '方法不允许',
  408: '请求超时',
  409: '冲突',
  413: '请求体过大',
  415: '不支持的类型',
  429: '请求过多',
  500: '服务器内部错误',
  502: '网关错误',
  503: '服务不可用',
  504: '网关超时',
};

/** `403` → `403 禁止访问`；未收录的码按类别兜底（4xx 请求错误 / 5xx 服务器错误）。 */
export function httpStatusText(status: number): string {
  const g = GLOSS[status] ?? (status >= 500 ? '服务器错误' : status >= 400 ? '请求错误' : status >= 300 ? '重定向' : '成功');
  return `${status} ${g}`;
}
